// Writes prisma/schema.postgres.prisma: the same tables as prisma/schema.prisma,
// but for PostgreSQL. Used by `npm run vercel-build`, so hosts without a
// permanent disk (Vercel) can use a hosted database while local development
// keeps using the SQLite file. prisma/schema.prisma stays the single source.

import { readFileSync, writeFileSync } from "node:fs";

const source = readFileSync("prisma/schema.prisma", "utf8");
if (!source.includes('provider = "sqlite"')) {
  throw new Error('Expected provider = "sqlite" in prisma/schema.prisma');
}
writeFileSync(
  "prisma/schema.postgres.prisma",
  "// Generated by scripts/make-postgres-schema.mjs. Do not edit; change prisma/schema.prisma instead.\n" +
    source.replace('provider = "sqlite"', 'provider = "postgresql"'),
);
console.log("Wrote prisma/schema.postgres.prisma");
